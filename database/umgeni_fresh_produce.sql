-- Umgeni Fresh Produce: practice database for SQL
-- A fictional fresh-produce distributor supplying businesses in KwaZulu-Natal.
-- All data is made up (synthetic), generated for learning purposes.
--
-- Tables:
--   farms        : the farms that grow the produce
--   products     : what is sold, and which farm supplies it
--   customers    : businesses that buy produce
--   orders       : one row per order (date and status)
--   order_items  : the products and quantities on each order

DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS farms;

CREATE TABLE farms (
  farm_id    INTEGER PRIMARY KEY,
  farm_name  TEXT NOT NULL,
  region     TEXT
);

CREATE TABLE products (
  product_id    INTEGER PRIMARY KEY,
  product_name  TEXT NOT NULL,
  category      TEXT,
  unit          TEXT,
  unit_price    REAL NOT NULL,   -- price in rand per unit
  farm_id       INTEGER REFERENCES farms(farm_id)
);

CREATE TABLE customers (
  customer_id    INTEGER PRIMARY KEY,
  customer_name  TEXT NOT NULL,
  customer_type  TEXT,           -- Restaurant, Retailer, Hotel, Caterer
  city           TEXT,
  signup_date    TEXT            -- YYYY-MM-DD
);

CREATE TABLE orders (
  order_id     INTEGER PRIMARY KEY,
  customer_id  INTEGER REFERENCES customers(customer_id),
  order_date   TEXT,             -- YYYY-MM-DD
  status       TEXT              -- Delivered or Cancelled
);

CREATE TABLE order_items (
  item_id     INTEGER PRIMARY KEY,
  order_id    INTEGER REFERENCES orders(order_id),
  product_id  INTEGER REFERENCES products(product_id),
  quantity    INTEGER NOT NULL
);

